"""
Replaces broken معدلات القبول 2025 table sections in all paramedical specialty pages.
Run from the project root: python fix_paramedical_tables.py
"""
import os

BASE = os.path.join(os.path.dirname(__file__), "university", "speciality")

def make_table(institute_name, rows):
    tr_rows = "\n".join(
        f'                <tr><td>{w}</td><td dir="ltr" style="text-align: right;">{v}</td></tr>'
        for w, v in rows
    )
    return (
        f'<div class="detail-card large-card">\n'
        f'    <h3><i class="fas fa-university"></i> {institute_name}</h3>\n'
        f'    <div class="table-container">\n'
        f'        <table class="styled-table">\n'
        f'            <thead>\n'
        f'                <tr>\n'
        f'                    <th>الولاية (مكان الإقامة)</th>\n'
        f'                    <th>معدل القبول 2025</th>\n'
        f'                </tr>\n'
        f'            </thead>\n'
        f'            <tbody>\n'
        f'{tr_rows}\n'
        f'            </tbody>\n'
        f'        </table>\n'
        f'    </div>\n'
        f'</div>'
    )

def build_section(data):
    cards = "\n\n".join(make_table(name, rows) for name, rows in data)
    return (
        '<div class="modern-section-header" style="margin-top: 60px;">\n'
        '    <h2>معدلات القبول 2025 (المرحلة الأولى)</h2>\n'
        '</div>\n\n'
        + cards
        + '\n\n'
    )

def replace_section(filename, new_html):
    path = os.path.join(BASE, filename)
    with open(path, encoding="utf-8") as f:
        content = f.read()
    start_marker = '<div class="modern-section-header" style="margin-top: 60px;">'
    end_marker = '<!-- Specialty Navigation Buttons -->'
    start = content.find(start_marker)
    end = content.find(end_marker)
    if start == -1 or end == -1:
        print(f"  MARKERS NOT FOUND in {filename}")
        return
    new_content = content[:start] + new_html + content[end:]
    with open(path, "w", encoding="utf-8") as f:
        f.write(new_content)
    print(f"  OK  {filename}")

