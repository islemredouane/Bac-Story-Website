def base_filiere(f):
    return re.sub(r"\s*--\s*pour bacheliers.*", "", f, flags=re.IGNORECASE).strip()


def compute_averages(rows, filiere_name):
    """Compute resolvedAverages (global min per stream) and wilayaAverages."""
    matching = [r for r in rows if base_filiere(r["filiere"]) == filiere_name]
    if not matching:
        return {}, {}

    streams = {"min1": [], "min2": [], "min3": []}
    wilaya_data = {}

    for r in matching:
        w = r.get("wilaya") or "National"
        if w not in wilaya_data:
            wilaya_data[w] = {"min1": [], "min2": [], "min3": []}
        for mn in ["min1", "min2", "min3"]:
            v = r.get(mn)
            if v is not None:
                streams[mn].append(float(v))
                wilaya_data[w][mn].append(float(v))

    resolved = {}
    for mn in ["min1", "min2", "min3"]:
        if streams[mn]:
            resolved[mn] = round(min(streams[mn]), 2)

    wilaya_avgs = {}
    for w in sorted(wilaya_data):
        wd = {}
        for mn in ["min1", "min2", "min3"]:
            vals = wilaya_data[w][mn]
            if vals:
                wd[mn] = round(min(vals), 2)
        if wd:
            wilaya_avgs[w] = wd

    return resolved, wilaya_avgs


def averages_text(resolved):
    """Build Arabic averages text string."""
    labels = {"min1": "شعبة رياضيات", "min2": "شعبة علوم تجريبية", "min3": "شعبة تقني رياضي"}
    parts = []
    for mn, label in labels.items():
        if mn in resolved:
            parts.append(f"{label}: {resolved[mn]}")
    return " / ".join(parts) if parts else "راجع بيانات القبول لولايتك"


