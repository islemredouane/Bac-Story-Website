# -----------------------------------------------------------------------
# Build full KB entry objects with computed averages
# -----------------------------------------------------------------------
def build_entry(defn):
    linked_keys = defn["linkedFiliereKeys"]
    # Compute averages across all linked filieres
    all_resolved = {}
    all_wilaya = {}

    for lk in linked_keys:
        r, w = compute_averages(ROWS, lk)
        # Merge: take min per stream
        for mn, v in r.items():
            if mn not in all_resolved or v < all_resolved[mn]:
                all_resolved[mn] = v
        for wname, wd in w.items():
            if wname not in all_wilaya:
                all_wilaya[wname] = {}
            for mn, v in wd.items():
                if mn not in all_wilaya[wname] or v < all_wilaya[wname][mn]:
                    all_wilaya[wname][mn] = v

    entry = {
        "id": defn["id"],
        "category": defn["category"],
        "name_ar": defn["name_ar"],
        "name_fr": defn["name_fr"],
        "sections": defn["sections"],
        "linkedFiliereKeys": linked_keys,
    }
    if all_resolved:
        entry["resolvedAverages"] = all_resolved
        entry["averages_text"] = averages_text(all_resolved)
    if all_wilaya:
        entry["wilayaAverages"] = all_wilaya
    if "_note" in defn:
        entry["_linkNote"] = defn["_note"]

    return entry


